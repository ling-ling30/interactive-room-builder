export type SimsCategory = 'desks' | 'chairs' | 'tech' | 'lighting' | 'decor' | (string & {});

export interface SimsProductVariant {
  id: number;
  name: string;
  weeklyPrice: number;
  monthlyPrice: number;
  dimensions?: string | null;
}

export interface SimsProduct {
  id: string;
  name: string;
  category: SimsCategory;
  footprint: { width: number; depth: number }; // In grid tiles / meters
  actualDimensions?: { widthM: number; depthM: number; heightM: number }; // Exact physical size in meters
  weeklyRent: number;
  monthlyRent: number;
  deposit: number;
  brand: string;
  modelType: string;
  layer: 'floor' | 'surface'; // 'floor' sits on tiles, 'surface' can sit on top of desks
  color: string;
  colorOptions?: string[];
  description: string;
  icon: string;
  heightCm?: number;

  // Real Monis Crawled Specs & 3D Assets
  imageUrl?: string;
  modelUrl?: string; // 3D model .glb / .gltf URL or uploaded blob/base64
  photos?: string[];
  dimensionsText?: string;
  variants?: SimsProductVariant[];
  sourceUrl?: string;
  weightKg?: number;
  material?: string;
  setupCost?: number;

  // True-to-life dimensional scaling calibration
  scaleMultiplier?: number; // Fine-tune scale factor (e.g. 1.0, 1.15, 0.85)
  fitMode?: 'proportional' | 'exact'; // 'proportional' preserves model aspect ratio, 'exact' matches WxHxD
}

export interface PlacedFurniture {
  instanceId: string;
  productId: string;
  gridX: number; // 0 to 9
  gridZ: number; // 0 to 9
  rotation: number; // 0, 90, 180, 270 (in degrees)
  color: string;
  surfaceY: number; // 0 for floor, or height of desk
  mountedOnDeskId?: string; // if placed on a desk
  selectedVariantId?: number; // if chosen a specific size/variant
}

